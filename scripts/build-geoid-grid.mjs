// Generates src/data/egm96Grid.js: the EGM96 geoid undulation on a 0.5°
// grid, small enough to load at startup. The full 15' model from
// egm96-universal is a 1.8 MB download; this grid is ~330 KB compressed and,
// with bilinear interpolation, stays within ~2 m of it (RMS ~0.1 m), inside
// the 2.5 m tolerance the geoid tests allow.
//
// Layout: 361 rows (90°N → 90°S) × 720 columns (180°W → 179.5°E), Int16
// little-endian centimetres. Each row is delta-encoded (first value absolute,
// then differences), which compresses far better. Stored as base64 in a JS
// module so it loads with a plain dynamic import in browsers and Node alike.
//
// Run after upgrading egm96-universal: node scripts/build-geoid-grid.mjs
import { writeFileSync } from 'node:fs';
import { meanSeaLevel } from 'egm96-universal';

export const STEP_DEG = 0.5;
export const ROWS = 180 / STEP_DEG + 1;
export const COLS = 360 / STEP_DEG;

/** The delta-encoded grid as raw bytes. */
export function buildGeoidGridBytes() {
  const delta = new Int16Array(ROWS * COLS);
  for (let r = 0; r < ROWS; r++) {
    let previous = 0;
    for (let c = 0; c < COLS; c++) {
      const cm = Math.round(
        meanSeaLevel(90 - r * STEP_DEG, -180 + c * STEP_DEG) * 100,
      );
      delta[r * COLS + c] = c === 0 ? cm : cm - previous;
      previous = cm;
    }
  }
  return Buffer.from(delta.buffer);
}

// Write the module only when run directly; tests import buildGeoidGridBytes.
if (process.argv[1]?.endsWith('build-geoid-grid.mjs')) {
  const target = new URL('../src/data/egm96Grid.js', import.meta.url);
  const base64 = buildGeoidGridBytes().toString('base64');
  writeFileSync(
    target,
    `// Generated by scripts/build-geoid-grid.mjs from egm96-universal. Do not edit.\n` +
      `// EGM96 geoid undulation, ${STEP_DEG}° grid, ${ROWS}×${COLS} Int16 LE cm, row-delta, base64.\n` +
      `export const STEP_DEG = ${STEP_DEG};\n` +
      `export const ROWS = ${ROWS};\n` +
      `export const COLS = ${COLS};\n` +
      // Prettier's layout for a long string, so format:check stays clean.
      `export const DATA =\n  '${base64}';\n`,
  );
  console.log(
    `Wrote ${target.pathname} (${(base64.length / 1024).toFixed(0)} KB base64)`,
  );
}
